#!/usr/bin/env node
/**
 * Live verification of the RVC *setup* template: write the real generated cells into a
 * Kaggle kernel, push it, and let it run for real (CPU + internet, no GPU quota).
 *
 * Run: node test/rvc-setup-run.mjs [--wait]
 */
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const workspace = path.resolve(here, '..', '..');
process.env.KAGGLE_RVC_HOME = workspace;
process.env.KAGGLE_RVC_USERNAME ??= '<owner>';

const { createServer } = await import('../src/server.mjs');
const [ct, st] = InMemoryTransport.createLinkedPair();
const server = createServer();
await server.connect(st);
const client = new Client({ name: 'rvc-setup-run', version: '0.1.0' }, { capabilities: {} });
await client.connect(ct);

const wait = process.argv.includes('--wait');
const SLUG = 'rvc-setup-verify';

async function call(name, args = {}, options) {
  const res = await client.callTool({ name, arguments: args }, undefined, options);
  const text = (res.content ?? []).filter((c) => c.type === 'text').map((c) => c.text).join('\n');
  console.log(`\n########## ${name}\n${text}`);
  return { res, text };
}

// Make sure this runs on CPU without booking a GPU shape.
await call('kernel_configure', { kernel: SLUG, gpu: false, machine_shape: '', internet: true, is_private: true });

// The real template cells, generated by the current code.
await call('rvc_notebook', { kernel: SLUG, stage: 'setup', exp_name: 'voice', sample_rate: '40k' });

const push = await call(
  'kernel_push',
  {
    kernel: SLUG,
    wait,
    timeout_sec: 2400,
    poll_sec: 30,
  },
  // The SDK client defaults to a 60 s request timeout; a blocking wait needs more.
  { timeout: (2400 + 120) * 1000 },
);

await client.close();
await server.close();

const ok = !/ERROR:/.test(push.text);
console.log(`\n================ PUSH ${ok ? 'ACCEPTED' : 'FAILED'} ================`);
process.exit(ok ? 0 : 1);
